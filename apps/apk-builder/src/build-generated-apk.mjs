const isTrustedAiyaHost = (host) => {
  const lower = String(host || '').toLowerCase();
  if (!lower) return false;
  return AIYA_TRUSTED_HOSTS.some((allowed) => lower === allowed || lower.endsWith(`.${allowed}`));
};

const validateProjectUrl = (value) => {
  let parsed;
  try {
    parsed = new URL(String(value || ''));
  } catch {
    throw new Error(`URL rejected: expected a valid https URL, got ${value || '(empty)'}.`);
  }
  if (parsed.protocol !== 'https:') {
    throw new Error(`URL rejected: project APKs must use https, got ${parsed.protocol}`);
  }
  if (!isTrustedAiyaHost(parsed.hostname)) {
    throw new Error(
      `URL rejected: host "${parsed.hostname}" is not in the AIYA trusted host list ` +
      `(${AIYA_TRUSTED_HOSTS.join(', ')}). Refusing to inject AiyaApkBridge into an arbitrary site.`,
    );
  }
  if (parsed.username || parsed.password) {
    throw new Error('URL rejected: embedded credentials are not allowed.');
  }
  return parsed.toString();
};

const detectGeneratedCapabilities = (html) => {
  const value = String(html || '');
  const bodyVision = /AiyaBodyVision(?:Runtime)?|\banalyzeFace\s*\(|\banalyzeGesture\s*\(|faceBlendshapes|weirdnessScore|gestureZh/i.test(value);
  const whistle = /AiyaBodyAudio|\bestimatePitch\s*\(|\bcreatePitchTracker\s*\(|口哨|哨声|吹哨|whistle|pitch\s*(?:tracker|detect|frequency)/i.test(value);
  const motion = /AiyaBodyMotion|deviceorientation|devicemotion|DeviceOrientationEvent|DeviceMotionEvent|gyroscope|accelerometer/i.test(value);
  const microphoneCapture = /getUserMedia\s*\([\s\S]{0,500}\baudio\s*:(?!\s*(?:false\b|null\b|0\b))/i.test(value)
    || /\bmicrophone\b|RESOURCE_AUDIO_CAPTURE/i.test(value);
  const cameraCapture = /getUserMedia\s*\([\s\S]{0,500}\bvideo\s*:(?!\s*(?:false\b|null\b|0\b))/i.test(value)
    || /\bfacingMode\b|RESOURCE_VIDEO_CAPTURE/i.test(value);
  return Object.freeze({
    bodyVision,
    whistle,
    motion,
    microphone: whistle || microphoneCapture,
    camera: bodyVision || cameraCapture,
  });
};

const prepareHtml = (html, capabilities = detectGeneratedCapabilities(html)) => {
  const mobileMeta = '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />';
  const tapStyle = '<style id="aiya-apk-safe-area">html,body{min-height:100%;}*{-webkit-tap-highlight-color:transparent;}body{margin:0;}</style>';
  let next = html;
  if (!/<meta\s+name=["']viewport["']/i.test(next)) {
    next = /<head[^>]*>/i.test(next)
      ? next.replace(/<head[^>]*>/i, (match) => `${match}\n  ${mobileMeta}`)
      : `${mobileMeta}\n${next}`;
  }
  if (!/aiya-apk-safe-area/.test(next)) {
    next = /<\/head>/i.test(next)
      ? next.replace(/<\/head>/i, `  ${tapStyle}\n</head>`)
      : `${tapStyle}\n${next}`;
  }
  if ((capabilities.bodyVision || capabilities.whistle || capabilities.motion) && !/aiya-v3-body-runtime/.test(next)) {
    next = /<head[^>]*>/i.test(next)
      ? next.replace(/<head[^>]*>/i, (match) => `${match}\n${bodyRuntimeHtml}`)
      : `${bodyRuntimeHtml}\n${next}`;
  }
  return next;
};

const findAndroidSdkRoot = () => {
  const candidates = [
    process.env.ANDROID_HOME,
    process.env.ANDROID_SDK_ROOT,
    process.platform === 'win32' ? join(homedir(), 'AppData', 'Local', 'Android', 'Sdk') : '/opt/android-sdk',
    process.platform === 'win32' ? undefined : join(homedir(), 'Android', 'Sdk'),
  ].filter(Boolean);
  return candidates.find((candidate) => existsSync(join(String(candidate), 'platforms')) && existsSync(join(String(candidate), 'build-tools'))) || null;
};

const findGradleExecutable = () => {
  const whereResult = spawnSync(process.platform === 'win32' ? 'where.exe' : 'which', ['gradle'], {
    encoding: 'utf8'
  });
  if (whereResult.status === 0) {
    const first = whereResult.stdout.split(/\r?\n/).map((line) => line.trim()).find(Boolean);
    if (first) return first;
  }

  const dists = join(homedir(), '.gradle', 'wrapper', 'dists');
  if (!existsSync(dists)) return null;

  const candidates = [];
  for (const dist of readdirSync(dists, { withFileTypes: true })) {
    if (!dist.isDirectory() || !dist.name.startsWith('gradle-')) continue;
    const distDir = join(dists, dist.name);
    for (const hashDir of readdirSync(distDir, { withFileTypes: true })) {
      if (!hashDir.isDirectory()) continue;
      const hashPath = join(distDir, hashDir.name);
      for (const versionDir of readdirSync(hashPath, { withFileTypes: true })) {
        if (!versionDir.isDirectory() || !versionDir.name.startsWith('gradle-')) continue;
        const executable = join(hashPath, versionDir.name, 'bin', process.platform === 'win32' ? 'gradle.bat' : 'gradle');
        if (existsSync(executable)) candidates.push(executable);
      }
    }
  }
  candidates.sort().reverse();
  return candidates[0] || null;
};

