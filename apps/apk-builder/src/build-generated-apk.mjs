const validateVectorIcon = (file) => {
  if (!/\.xml$/i.test(file)) throw new Error(`Vector icon rejected: expected an XML file, got ${file}`);
  const stat = statSync(file);
  if (stat.size > 64_000) throw new Error(`Vector icon rejected: file is too large (${stat.size} bytes)`);
  const xml = readFileSync(file, 'utf8').replace(/^\uFEFF/, '').trim();
  if (!/^<vector\b/i.test(xml) || !/<\/vector>$/i.test(xml)) {
    throw new Error('Vector icon rejected: root element must be <vector>.');
  }
  const contentWithoutAndroidNamespace = xml.replace('http://schemas.android.com/apk/res/android', '');
  if (/<(?:bitmap|clip-path|aapt:attr)|@(?:drawable|mipmap|raw)|(?:https?:|file:|data:)/i.test(contentWithoutAndroidNamespace)) {
    throw new Error('Vector icon rejected: external or unsupported resources are not allowed.');
  }
  if (/<(?!\/?(?:vector|path|group)\b)[^>]+>/i.test(xml)) {
    throw new Error('Vector icon rejected: only vector, group and path elements are allowed.');
  }
  return xml;
};

const resolveKeystoreConfig = (args, projectDir) => {
  const token = args['release-keystore'];
  if (!token) return null;
  const abs = resolve(repoRoot, token);
  if (!existsSync(abs)) {
    throw new Error(`Release keystore not found: ${abs}`);
  }
  const passEnv = (args['keystore-pass'] && String(args['keystore-pass'])) || 'AIYA_KEYSTORE_PASS';
  if (!process.env[passEnv]) {
    throw new Error(
      `Release keystore configured but env var ${passEnv} is unset. ` +
      'Refusing to build a signed APK without an explicit keystore password.',
    );
  }
  const alias = (args['key-alias'] && String(args['key-alias'])) || 'aiya-generated';
  const relTarget = join(projectDir, 'app', 'release.keystore');
  copyFileSync(abs, relTarget);
  return { relativeStore: 'release.keystore', passEnv, alias, absoluteStore: abs };
};

